local xsp = require("xspcomm")
local wide = xsp.XData(65, xsp.XData.In)
wide:Set("0x10000000000001234")
assert(wide:String() == "010000000000001234", wide:String())
wide:ImmSet("0x10000000000005678")
assert(wide:String() == "010000000000005678", wide:String())
wide:Set(7)
assert(wide:U() == 7)

local signal = xsp.XData(8, xsp.XData.In)
local view = signal:ArrayView([[{"kind":"array","packed":true,"width":8,"left":1,"right":0,
 "element":{"kind":"array","packed":true,"width":4,"left":-2,"right":1,
 "element":{"kind":"bits","packed":true,"width":0}}}]])
signal:Set(0)
view:Array(1):Data(-2):Set(1)
view:Array(0):Data(1):Set(1)
assert(signal:U() == 0x81)
assert(view:Array(1):Data(-2):U() == 1)
local ok = pcall(function() view:At(2) end)
assert(not ok)
local node = view:At(1)
assert(node:HasValue())
ok = pcall(function() node:Struct() end)
assert(not ok)
ok = pcall(function() node:Data() end)
assert(not ok)
assert(node:PackedData():W() == 4)
local empty = xsp.XView()
assert(not empty:HasValue())
ok = pcall(function() empty:Array() end)
assert(not ok)
